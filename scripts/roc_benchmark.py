#!/usr/bin/env python3
"""Generate the attack-strength ROC analysis: docs/ROC_ANALYSIS.md, docs/roc_data.csv and two PNG plots."""
import csv
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from shorlynot_skeleton.analysis import roc

DOCS = os.path.join(os.path.dirname(__file__), "..", "docs")
BLUE, ORANGE, INK, MUTED, GRID, SURFACE = "#2a78d6", "#eb6834", "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
N, P0, DELTA = 64, 0.02, 0.01


def style(ax, xlabel, ylabel, title):
    ax.set_facecolor(SURFACE)
    ax.figure.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.tick_params(colors=MUTED)
    ax.set_xlabel(xlabel, color=MUTED)
    ax.set_ylabel(ylabel, color=MUTED)
    ax.set_title(title, color=INK, loc="left", fontsize=12)


def plot_partial(data):
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(data["x"], data["partial_info_hoeffding"], color=BLUE, linewidth=2, label="Hoeffding threshold")
    ax.plot(data["x"], data["partial_info_exact"], color=ORANGE, linewidth=2, linestyle="--", label="Exact-binomial threshold")
    style(ax, "Fraction of true syndromes the forger knows", "Forger acceptance probability",
          f"Forger acceptance vs attacker information (n={N}, delta={DELTA})")
    ax.set_ylim(-0.02, 1.02)
    ax.legend(frameon=False, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(os.path.join(DOCS, "roc_partial_info.png"), dpi=150)
    plt.close(fig)


def plot_noise(nz):
    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(nz["true_p0"], nz["frr_hoeffding"], color=BLUE, linewidth=2, marker="o", label="Hoeffding threshold")
    ax.plot(nz["true_p0"], nz["frr_exact"], color=ORANGE, linewidth=2, linestyle="--", marker="o", label="Exact-binomial threshold")
    ax.axvline(P0, color=MUTED, linewidth=1, linestyle=":")
    ax.text(P0 + 0.005, 0.5, "assumed p0", color=MUTED, fontsize=9)
    style(ax, "True hardware noise p0", "Honest false-reject rate",
          f"Honest rejection when real noise exceeds the assumed {P0:.0%}")
    ax.set_ylim(-0.02, 1.02)
    ax.legend(frameon=False, labelcolor=INK, loc="center right")
    fig.tight_layout()
    fig.savefig(os.path.join(DOCS, "roc_noise.png"), dpi=150)
    plt.close(fig)


def main():
    data = roc.sweep(N, P0, DELTA)
    nz = roc.frr_vs_true_noise(N, P0, DELTA)
    val = roc.validate_against_engine(N, P0, trials=300)
    plot_partial(data)
    plot_noise(nz)

    with open(os.path.join(DOCS, "roc_data.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["x", "partial_info_hoeffding", "partial_info_exact", "tamper_hoeffding", "tamper_exact"])
        for i, x in enumerate(data["x"]):
            w.writerow([round(x, 3)] + [f"{data[k][i]:.6g}" for k in
                       ("partial_info_hoeffding", "partial_info_exact", "tamper_hoeffding", "tamper_exact")])

    rows = []
    for n in (32, 64, 128):
        t = roc.tolerated_information(n, P0, DELTA)
        rows.append(f"| {n} | {t['hoeffding']['tau']:.4f} | {t['exact']['tau']:.4f} | "
                    f"{t['hoeffding']['f_needed']:.0%} | {t['exact']['f_needed']:.0%} | "
                    f"{t['hoeffding']['r_tolerated']:.1%} | {t['exact']['r_tolerated']:.1%} |")
    frr_h = roc.accept_probability(P0 / 2, data["tau"]["hoeffding"], N)
    md = f"""# ROC_ANALYSIS.md: Attack-Strength Analysis of the Q-STDF Detector

Generated by `python scripts/roc_benchmark.py`. All curves are exact binomial calculations, cross-checked
against the project's own verifier model (`QiskitAerEngine.simulate_bob_verification`).

## Why this exists

The headline "100% detection" compares honest signatures with attackers who know nothing. That split is true by
construction. This analysis varies **attacker strength** instead, and shows where the detector actually stops working.

## Attackers modelled

- **Partial-information forger.** Knows each true syndrome with probability f, guesses the rest.
  Per-position mismatch probability is `f*p0/2 + (1-f)/2`.
- **In-flight tamperer.** Flips each syndrome bit with probability r. Mismatch probability is `(1-r)*p0/2 + r*(1-p0/2)`.

## Model check

| Quantity | Closed form | Measured through verifier model |
|---|---|---|
| Honest mismatch rate | {val['honest_theory']:.4f} | {val['honest_measured']:.4f} |
| Random-guess mismatch rate | {val['guess_theory']:.4f} | {val['guess_measured']:.4f} |
| Partial information, f=0.5 | {val['partial_theory']:.4f} | {val['partial_measured']:.4f} |
| Tampering, r=0.3 | {val['tamper_theory']:.4f} | {val['tamper_measured']:.4f} |

## Finding 1: the Hoeffding threshold is far looser than it needs to be

With depolarizing noise p0 = {P0}, an honest bit is wrong with probability p0/2 = {P0/2}, not p0. Hoeffding adds a
generous slack on top. At n = {N}, delta = {DELTA}, the real false-reject rate of the Hoeffding threshold
({data['tau']['hoeffding']:.4f}) is about {1-frr_h:.1e}, against a budget of {DELTA}. The slack is paid for by forgery security.

An exact-binomial threshold ({data['tau']['exact']:.4f}, i.e. at most {round(data['tau']['exact']*N)} mismatches of {N})
keeps the same false-reject guarantee and is much tighter.

| n | tau (Hoeffding) | tau (exact) | Forger info needed, Hoeffding | Forger info needed, exact | MITM flip rate tolerated, Hoeffding | MITM flip rate tolerated, exact |
|---|---|---|---|---|---|---|
{chr(10).join(rows)}

"Info needed" is the fraction of true syndromes a forger must know to be accepted half the time.
"Flip rate tolerated" is the largest syndrome-flip rate that is still accepted half the time.

![Forger acceptance vs information](roc_partial_info.png)

## Finding 2: a tight threshold is fragile if the noise assumption is wrong

The exact threshold is only as good as the assumed p0. If real hardware is noisier than assumed, honest users get rejected.

![False-reject rate vs true noise](roc_noise.png)

Hoeffding tolerates a 5x noise error with a false-reject rate near 1e-9. The exact threshold at 5x noise (true p0 = 0.10)
rejects about {roc.frr_vs_true_noise(N, P0, DELTA)['frr_exact'][3]:.0%} of honest signatures. Use the exact threshold only with a measured,
periodically re-calibrated noise estimate (for example an upper confidence bound from calibration runs), never a hard-coded constant.

## Limits of this analysis

- Independent, identically distributed errors are assumed. Real hardware has drift and correlated noise.
- "Partial information" is an abstract fraction. How an attacker would obtain it on real hardware is outside this model.
- Verification still reads the true syndromes from the Bob-side session store, which simulates entanglement.
  This analysis measures the statistical test, not the physical security of a deployed quantum channel.

Data: `roc_data.csv`. Opt-in: `QdsT1Protocol.verify(..., threshold_mode="exact")`.
"""
    with open(os.path.join(DOCS, "ROC_ANALYSIS.md"), "w") as fh:
        fh.write(md)
    print("wrote ROC_ANALYSIS.md, roc_data.csv, roc_partial_info.png, roc_noise.png")


if __name__ == "__main__":
    sys.exit(main())
